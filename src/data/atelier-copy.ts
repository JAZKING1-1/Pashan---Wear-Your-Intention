export type AtelierKey = keyof typeof rows;
const codes: Locale[] = [
  "en",
  "hi",
  "pa",
  "mr",
  "gu",
  "bn",
  "ta",
  "te",
  "fr",
  "ar",
];
export function atelierText(
  locale: Locale,
  key: AtelierKey,
  values: Record<string, string | number> = {},
): string {
  let text: string = rows[key][codes.indexOf(locale)] ?? rows[key][0];
  for (const [k, v] of Object.entries(values))
    text = text.replaceAll("{" + k + "}", String(v));
  return text;
}
export const useAtelierCopy = () => {
  const { locale } = useI18n();
  return {
    locale,
    a: (key: AtelierKey, values?: Record<string, string | number>) =>
      atelierText(locale, key, values),
  };
};
export const atelierTranslationRows = rows;
